#!/usr/bin/env node
/* ============================================================
   build-section-refs.mjs  —  READ-ONLY generator
   ------------------------------------------------------------
   Scans chapter/*-data.js for the CHAPTER object and emits the
   allowlist of every reportable section:

     report/section-refs.json        (labels for the admin UI)
     report/worker/section-refs.sql  (D1 seed)

   It NEVER writes to chapter/. Re-run it whenever a chapter is
   added or its section list changes, then re-seed D1:

     node report/build-section-refs.mjs
     cd report/worker && wrangler d1 execute klarweg-reports \
       --file=./section-refs.sql --remote
   ============================================================ */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CH = resolve(ROOT, 'chapter');

const all = readdirSync(CH);
const htmls = all.filter(f => /^chapter-[abc][12]-.*\.html$/.test(f));
const htmlSet = new Set(htmls);
const datas = all.filter(f => /^chapter-[abc][12]-.*-data\.js$/.test(f));

// Each data file pairs with its page. Most share a basename; a few pages carry
// a longer slug than the data file (chapter-a1-1-data.js -> chapter-a1-1-alphabet.html).
const pairs = datas.map(d => {
  const base = d.replace(/-data\.js$/, '');
  let h = base + '.html';
  if (!htmlSet.has(h)) {
    const cands = htmls.filter(x => x.startsWith(base + '-'));
    if (cands.length !== 1) throw new Error('Cannot resolve page for ' + d + ' (candidates: ' + cands.join(', ') + ')');
    h = cands[0];
  }
  return [d, h];
});
// The original A1 Ch3 page reads the unsuffixed chapter-data.js.
if (all.includes('chapter-data.js') && htmlSet.has('chapter-a1-3-nominativ.html')) {
  pairs.push(['chapter-data.js', 'chapter-a1-3-nominativ.html']);
}

const uesc = s => String(s)
  .replace(/\\u([0-9a-fA-F]{4})/g, (m, h) => String.fromCharCode(parseInt(h, 16)))
  .replace(/\\'/g, "'").replace(/\\"/g, '"');

const rows = [];
for (const [d, h] of pairs) {
  const t = readFileSync(resolve(CH, d), 'utf8');
  const id = (t.match(/\bid:\s*'([^']+)'/) || [])[1];
  const num = (t.match(/\bnumber:\s*(\d+)/) || [])[1];
  const title = (t.match(/\btitle:\s*'((?:[^'\\]|\\.)*)'/) || [])[1];
  const sb = (t.match(/sections:\s*\[([\s\S]*?)\n\s*\]/) || [])[1];
  if (!id || !sb) throw new Error('Could not parse CHAPTER in ' + d);
  const level = id.slice(0, 2);
  const secs = [...sb.matchAll(/\{\s*id:\s*'([^']+)'\s*,\s*label:\s*'((?:[^'\\]|\\.)*)'/g)];
  if (!secs.length) throw new Error('No sections parsed in ' + d);
  for (const [, sid, label] of secs) {
    rows.push({
      ref: `klarweg:${level}/${id}/${sid}`,
      level, chapter_id: id, chapter_no: num ? +num : null,
      chapter_title: uesc(title || id),
      section_id: sid, section_label: uesc(label),
      page_path: 'chapter/' + h
    });
  }
}

const dups = rows.length - new Set(rows.map(r => r.ref)).size;
if (dups) throw new Error(dups + ' duplicate refs');

writeFileSync(resolve(ROOT, 'report/section-refs.json'),
  JSON.stringify({ generated: new Date().toISOString(), count: rows.length, chapters: pairs.length, refs: rows }));

const q = s => s == null ? 'NULL' : "'" + String(s).replace(/'/g, "''") + "'";
let sql = '-- GENERATED by report/build-section-refs.mjs — do not edit by hand.\n' +
  '-- Load with: wrangler d1 execute klarweg-reports --file=./section-refs.sql --remote\n' +
  'BEGIN TRANSACTION;\nDELETE FROM section_refs;\n';
for (const r of rows) {
  sql += `INSERT INTO section_refs VALUES(${q(r.ref)},${q(r.level)},${q(r.chapter_id)},${r.chapter_no ?? 'NULL'},${q(r.chapter_title)},${q(r.section_id)},${q(r.section_label)},${q(r.page_path)});\n`;
}
writeFileSync(resolve(ROOT, 'report/worker/section-refs.sql'), sql + 'COMMIT;\n');

console.log(`section-refs: ${pairs.length} chapters, ${rows.length} sections`);
