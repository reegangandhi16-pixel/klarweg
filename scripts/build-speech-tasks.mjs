#!/usr/bin/env node
/* Generates access/worker/src/speech-tasks.js — every chapter id and how many
   Speaking tasks it has, read from the real chapter data (CHAPTER.speaking).
   The Access Worker uses it to refuse unknown chapters and invented task
   numbers on /speech/*. A task's id is its position in CHAPTER.speaking
   (0-based) — the same index the page already uses ("speaking.<index>").

   Run after adding a chapter or changing a chapter's Speaking tasks:
     node scripts/build-speech-tasks.mjs
   then redeploy klarweg-access. scripts/speech-task-cap.test.mjs fails while
   the file is out of date. */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'access/worker/src/speech-tasks.js');

export function speakingCounts() {
  const dir = path.join(ROOT, 'chapter');
  const pages = fs.readdirSync(dir).filter((f) => /^chapter-[a-c][0-9]-.*\.html$/.test(f)).sort();
  const out = {};
  for (const page of pages) {
    const html = fs.readFileSync(path.join(dir, page), 'utf8');
    const src = html.match(/<script src="([^"]*data[^"]*\.js)[^"]*"/)[1].split('?')[0];
    const ctx = { console: { log() {}, warn() {} } }; ctx.window = ctx; vm.createContext(ctx);
    vm.runInContext(fs.readFileSync(path.join(dir, src), 'utf8') + '\n;this.__C = CHAPTER;', ctx);
    const C = ctx.__C;
    if (page !== 'chapter-' + C.id + '.html') throw new Error(`${page}: CHAPTER.id is "${C.id}"`);
    out[C.id] = Array.isArray(C.speaking) ? C.speaking.length : 0;
  }
  return out;
}

export function render(counts) {
  const ids = Object.keys(counts).sort();
  const total = ids.reduce((n, id) => n + counts[id], 0);
  return `/* GENERATED by scripts/build-speech-tasks.mjs — do not edit by hand.
   Chapter id → number of Speaking tasks (task ids 0 … n-1, the position in
   CHAPTER.speaking). ${ids.length} chapters, ${total} tasks. */
export const SPEECH_TASKS = Object.freeze({
${ids.map((id) => `  ${JSON.stringify(id)}: ${counts[id]}`).join(',\n')}
});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const counts = speakingCounts();
  fs.writeFileSync(OUT, render(counts));
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.keys(counts).length} chapters, ${Object.values(counts).reduce((a, b) => a + b, 0)} tasks`);
}
